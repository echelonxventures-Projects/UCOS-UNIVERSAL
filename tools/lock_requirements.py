#!/usr/bin/env python3
"""lock_requirements — regenerate tools/requirements.txt (hash-locked) from tools/requirements.in.

Resolves the exact closure in a throwaway virtualenv with an isolated environment, then records the sha256 of
every published distribution of each pinned version from the PyPI JSON API, so the lock works on every platform
CI may use. Usage: python3 tools/lock_requirements.py
"""
import json, os, re, subprocess, sys, tempfile, urllib.request

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IN, OUT = os.path.join(ROOT, 'tools', 'requirements.in'), os.path.join(ROOT, 'tools', 'requirements.txt')

def main():
    env = {k: v for k, v in os.environ.items() if not k.startswith('PYTHON')}
    env['PYTHONNOUSERSITE'] = '1'
    with tempfile.TemporaryDirectory() as td:
        subprocess.run([sys.executable, '-m', 'venv', td], check=True, env=env)
        py = os.path.join(td, 'bin', 'python')
        subprocess.run([py, '-m', 'pip', 'install', '--quiet', '--disable-pip-version-check', '-r', IN], check=True, env=env)
        freeze = subprocess.run([py, '-m', 'pip', 'freeze', '--all', '--local'], check=True, env=env,
                                capture_output=True, text=True).stdout.split()
    pins = sorted([p for p in freeze if '==' in p and not p.lower().startswith('pip==')], key=str.lower)
    direct = {re.split('==', l)[0].strip().lower().replace('_', '-') for l in open(IN) if '==' in l and not l.startswith('#')}
    out = ['#', f'# Hash-locked CI toolchain for Python {sys.version_info[0]}.{sys.version_info[1]} (.python-version).',
           '# Generated by tools/lock_requirements.py from tools/requirements.in. Do not edit by hand.',
           '# Install: pip install --require-hashes --no-deps -r tools/requirements.txt', '#']
    for pin in pins:
        name, ver = pin.split('==')
        with urllib.request.urlopen(f'https://pypi.org/pypi/{name}/{ver}/json', timeout=60) as r:
            data = json.load(r)
        hashes = sorted({u['digests']['sha256'] for u in data['urls']})
        if not hashes:
            sys.exit(f'no distributions published for {pin}')
        out.append(f'{name}=={ver} \\')
        out += [f'    --hash=sha256:{h}' + (' \\' if i < len(hashes) - 1 else '') for i, h in enumerate(hashes)]
        out.append(f'    # {"direct" if name.lower().replace("_", "-") in direct else "via direct dependencies"}')
    open(OUT, 'w').write('\n'.join(out) + '\n')
    print(f'{len(pins)} packages locked -> {os.path.relpath(OUT, ROOT)}')

if __name__ == '__main__':
    main()
