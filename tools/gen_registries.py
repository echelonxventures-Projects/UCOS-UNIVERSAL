#!/usr/bin/env python3
"""gen_registries — derive machine-readable registries from the universe constitutions and capability manifests.

Outputs (deterministic; seed of generator `gen.schema.object-types`, U59):
  spec/registries/errors.yaml           every error code named in a spec, with owner, category, HTTP/gRPC mapping
  spec/object-types/<type>.schema.json  one JSON Schema skeleton per object type declared in a manifest

The constitutions stay normative. Attributes are parsed from the `Type { field: Type, ... }` notation of each spec,
so a schema is only as precise as its spec: value types (TimePoint, Money, ...) become $refs, `a|b|c` becomes an enum,
everything else is carried as an untyped property whose description quotes the spec. Error categories come from
name heuristics and are marked `derived: heuristic` until a steward confirms them.

Usage: python3 tools/gen_registries.py [--check]   (--check: exit 1 if the files on disk are out of date)
"""
import glob, json, os, re, sys
import yaml

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
VT = 'https://schemas.ucos.io/meta/value-types.schema.json#/$defs/'
CANON = 'https://schemas.ucos.io/meta/canonical-object.schema.json'
VALUE_TYPES = ['TimePoint', 'TimeRange', 'BusinessDuration', 'Duration', 'LocalDateTime', 'LocalDate', 'LocalTimeWindow', 'LocalTime',
               'Recurrence', 'Money', 'Quantity', 'Percentage', 'CurrencyCode', 'LocaleTag', 'LocalizedText', 'GeoRef', 'Coordinate',
               'UGID', 'FrameRef', 'TemporalRef', 'Classification']

# ------------------------------------------------------------------ sources
def spec_docs():
    docs = sorted(glob.glob(os.path.join(ROOT, 'constitutions', 'U*', 'constitution.md')))
    docs += sorted(glob.glob(os.path.join(ROOT, 'engineering', '*.md')))
    docs.append(os.path.join(ROOT, 'UCOS-MASTER-ARCHITECTURE.md'))
    return docs

def owner_of(path):
    m = re.search(r'constitutions/(U\d\d-[^/]+)/', path)
    return m.group(1) if m else 'kernel'

# ------------------------------------------------------------------ errors
CODE = re.compile(r'`([A-Z][A-Z0-9]{1,7}_[A-Z0-9_]{2,})`')
CATEGORIES = [  # (keyword in code, category, http, grpc, retryable)
    (('NOT_FOUND', 'UNKNOWN_'), 'not-found', 404, 'NOT_FOUND', False),
    (('DUPLICATE', 'CONFLICT', 'ALREADY', 'VERSION_MISMATCH', 'CONCURRENT'), 'conflict', 409, 'ALREADY_EXISTS', False),
    (('FORBIDDEN', 'DENIED', 'NOT_AUTHORIZED', 'SCOPE_MISMATCH', 'LEVEL_INSUFFICIENT', 'ACR_INSUFFICIENT', 'SOD_', 'QUORUM', 'WIDENS', 'CONSENT'), 'authorization', 403, 'PERMISSION_DENIED', False),
    (('UNAUTHENTICATED', 'MFA', 'TOKEN_INVALID', 'SESSION'), 'authentication', 401, 'UNAUTHENTICATED', False),
    (('UNAVAILABLE', 'TIMEOUT', 'STALE', 'CAPACITY', 'RATE_LIMIT', 'THROTTL', 'BUDGET', 'EXHAUSTED', 'PROVIDER'), 'unavailable', 503, 'UNAVAILABLE', True),
    (('EXPIRED', 'CLOSED', 'LOCKED', 'STATE', 'NOT_ALLOWED', 'PHASE', 'FROZEN', 'REQUIRED', 'MISSING', 'NOT_MET', 'GATE', 'BLOCKED', 'SUSPENDED', 'HOLD'), 'precondition', 422, 'FAILED_PRECONDITION', False),
]

def categorize(code):
    for keys, cat, http, grpc, retry in CATEGORIES:
        if any(k in code for k in keys):
            return cat, http, grpc, retry
    return 'validation', 400, 'INVALID_ARGUMENT', False

def build_errors():
    found = {}
    for path in spec_docs():
        for n, line in enumerate(open(path, encoding='utf-8'), 1):
            if 'rror' not in line:
                continue
            for m in CODE.finditer(line):
                code = m.group(1)
                if code in found:
                    continue
                rest = line[m.end():m.end() + 160]
                note = re.match(r'\s*\(([^)]{3,140})\)', rest)
                cat, http, grpc, retry = categorize(code)
                found[code] = {'code': code, 'prefix': code.split('_')[0], 'owner': owner_of(path), 'category': cat,
                               'http': http, 'grpc': grpc, 'retryable': retry, 'derived': 'heuristic',
                               'source': f'{os.path.relpath(path, ROOT)}:{n}'}
                if note:
                    found[code]['note'] = note.group(1).strip()
    entries = sorted(found.values(), key=lambda e: e['code'])
    return {'apiVersion': 'ucos.io/v1', 'kind': 'ErrorRegistry',
            'description': 'Generated by tools/gen_registries.py from error codes named in the specs. Do not edit by hand; '
                           'change the spec and regenerate. Responses use RFC 9457 problem+json with `code` set to the entry code.',
            'count': len(entries), 'errors': entries}

# ------------------------------------------------------------------ object types
def split_top(s, sep=','):
    out, depth, cur = [], 0, ''
    for ch in s:
        if ch in '{[(':
            depth += 1
        elif ch in '}])':
            depth -= 1
        if ch == sep and depth == 0:
            out.append(cur); cur = ''
        else:
            cur += ch
    if cur.strip():
        out.append(cur)
    return [x.strip() for x in out if x.strip()]

def brace_body(text, i):
    """text[i] == '{' -> contents up to the matching brace."""
    depth = 0
    for j in range(i, len(text)):
        if text[j] == '{':
            depth += 1
        elif text[j] == '}':
            depth -= 1
            if depth == 0:
                return text[i + 1:j]
    return None

def find_definition(text, name, full):
    """Locate an object definition in one of the four notations used by the specs.
    Returns ('block', '<fields>') or ('table', [(names, type), ...]) or None."""
    # 1/2. a heading naming the type, followed by an attribute table or a `{ ... }` block
    h = re.search(r'^#{2,5} [^\n]*`(?:' + re.escape(full) + '|' + re.escape(name) + r')`[^\n]*$', text, re.M)
    if h:
        end = re.search(r'^#{1,5} ', text[h.end():], re.M)
        sect = text[h.end(): h.end() + end.start()] if end else text[h.end():]
        rows = [l for l in sect.splitlines() if l.startswith('|')]
        if len(rows) > 2 and 'attribute' in rows[0].lower():
            out = []
            for r in rows[2:]:
                cells = [c.strip() for c in r.strip().strip('|').split('|')]
                if len(cells) >= 2:
                    out.append((re.findall(r'`([A-Za-z][A-Za-z0-9]*)\??`', cells[0]), cells[1]))
            return ('table', out)
        b = re.search(r'^`\{', sect, re.M)
        if b and b.start() < 400:
            body = brace_body(sect, b.start() + 1)
            if body:
                return ('block', body)
    # 3. inline `Name { ... }`, `Name (note) { ... }` or **`Name`** `{ ... }`
    m = re.search(r'`' + re.escape(name) + r'(?:\s*\([^)`]*\))?\s*\{', text) \
        or re.search(r'`' + re.escape(name) + r'`\s*\([^)\n]*\)\s*`\{', text) \
        or re.search(r'\*\*`' + re.escape(name) + r'`\*\*[^`\n]{0,40}`\{', text)
    if m:
        body = brace_body(text, m.end() - 1)
        if body:
            return ('block', body)
    # 4. Mermaid classDiagram `class Name { a; b }`
    m = re.search(r'^\s*class ' + re.escape(name) + r'\s*\{', text, re.M)
    if m:
        body = brace_body(text, m.end() - 1)
        if body:
            return ('block', re.sub(r'[;\n]+', ',', body))
    # 5. YAML flow mapping `Name: { ... }` inside a code block
    m = re.search(r'^\s*' + re.escape(name) + r':\s*\{', text, re.M)
    if m:
        body = brace_body(text, m.end() - 1)
        if body:
            return ('block', body)
    return None

def camel(words):
    w = re.sub(r'[^A-Za-z0-9 ]+', ' ', words).split()
    return (w[0][0].lower() + w[0][1:] + ''.join(x[:1].upper() + x[1:] for x in w[1:])) if w else None

def prop_schema(typ, raw):
    t = typ.strip()
    arr = t.startswith('[') and t.endswith(']')
    inner = t[1:-1].strip() if arr else t
    s = None
    for vt in VALUE_TYPES:
        if re.match(r'^' + vt + r'\b', inner):
            s = {'$ref': VT + vt}
            break
    if s is None and re.fullmatch(r'[a-z0-9-]+(\|[a-z0-9-]+)+', inner):
        s = {'type': 'string', 'enum': inner.split('|')}
    if s is None and inner in ('bool', 'boolean'):
        s = {'type': 'boolean'}
    if s is None:
        s = {'description': raw}
    return {'type': 'array', 'items': s} if arr else s

def parse_attributes(body):
    props = {}
    for f in split_top(body):
        if ':' in f and not f.startswith('{'):
            name, typ = f.split(':', 1)
        else:
            name, typ = re.split(r'[\s(\[{]', f + ' ', maxsplit=1)[0], ''
            if not re.fullmatch(r'[A-Za-z][A-Za-z0-9?]*', name):
                name = re.sub(r'\(.*?\)|\[.*|\{.*', '', f)
        name = name.strip().rstrip('?')
        key = name if re.fullmatch(r'[A-Za-z][A-Za-z0-9]*', name) else camel(name)
        if not key or key in props:
            continue
        props[key] = prop_schema(typ, f) if typ else {'description': f}
    return props

def build_object_types():
    out = {}
    for mp in sorted(glob.glob(os.path.join(ROOT, 'spec', 'capabilities', 'packs', '*.yaml'))):
        m = yaml.safe_load(open(mp))
        md = m['metadata']
        uni = md.get('universe', '')
        cdoc = sorted(glob.glob(os.path.join(ROOT, 'constitutions', uni.split('-')[0] + '-*', 'constitution.md')))
        text = open(cdoc[0], encoding='utf-8').read() if cdoc else ''
        for ot in m['spec'].get('provides', {}).get('objectTypes', []) or []:
            short = ot.split('.')[-1]
            found = find_definition(text, short, ot) if text else None
            attrs = {}
            if found and found[0] == 'block':
                attrs = parse_attributes(found[1])
            elif found:
                for names, typ in found[1]:
                    for n in names:
                        attrs.setdefault(n, prop_schema(typ.strip('`'), f'{n}: {typ}'))
            body = bool(attrs)
            schema = {
                '$schema': 'https://json-schema.org/draft/2020-12/schema',
                '$id': f'https://schemas.ucos.io/object-types/{ot}.schema.json',
                'title': ot,
                'description': f'Generated by tools/gen_registries.py from {os.path.relpath(mp, ROOT)}'
                               + (f' and {os.path.relpath(cdoc[0], ROOT)}' if cdoc else '')
                               + '. Skeleton: the constitution is normative.',
                'allOf': [{'$ref': CANON}],
                'properties': {'type': {'const': ot},
                               'attributes': {'type': 'object', 'properties': attrs, 'additionalProperties': True}},
                'x-ucos': {'universe': uni, 'capability': md['id'], 'phase': md['phase'],
                           'spec': os.path.relpath(cdoc[0], ROOT) if cdoc else None,
                           'attributesFromSpec': bool(body)},
            }
            out[ot] = schema
    return out

# ------------------------------------------------------------------ io
def render():
    files = {}
    files['spec/registries/errors.yaml'] = yaml.safe_dump(build_errors(), sort_keys=False, allow_unicode=True, width=200)
    for ot, s in build_object_types().items():
        files[f'spec/object-types/{ot}.schema.json'] = json.dumps(s, indent=2, ensure_ascii=False) + '\n'
    return files

def stale(files):
    bad = [p for p, c in files.items()
           if not os.path.exists(os.path.join(ROOT, p)) or open(os.path.join(ROOT, p), encoding='utf-8').read() != c]
    extra = [os.path.relpath(p, ROOT) for p in glob.glob(os.path.join(ROOT, 'spec', 'object-types', '*.schema.json'))
             if os.path.relpath(p, ROOT) not in files]
    return bad, extra

def main():
    files = render()
    if '--check' in sys.argv:
        bad, extra = stale(files)
        for p in bad + extra:
            print('out of date:', p)
        sys.exit(1 if bad or extra else 0)
    bad, extra = stale(files)          # rewrite only what changed (avoids churn on synced folders)
    for p in extra:
        os.remove(os.path.join(ROOT, p))
    for p in bad:
        os.makedirs(os.path.dirname(os.path.join(ROOT, p)), exist_ok=True)
        open(os.path.join(ROOT, p), 'w', encoding='utf-8').write(files[p])
    n_ot = len(files) - 1
    with_attrs = sum(1 for p, c in files.items() if p.endswith('.json') and '"attributesFromSpec": true' in c)
    print(f'errors: {yaml.safe_load(files["spec/registries/errors.yaml"])["count"]}  object types: {n_ot} ({with_attrs} with attributes from spec)')

if __name__ == '__main__':
    main()
